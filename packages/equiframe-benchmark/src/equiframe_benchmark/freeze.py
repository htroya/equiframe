"""Seal experimental configuration after checking captured evidence, without fitting.

A pilot seal establishes technical integrity only. Hashes do not authenticate data
licenses, review identities, independence claims or the origin of a fitted forest.
No transformation, imported callback or human review is generated by this module.
"""

