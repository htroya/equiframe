class FreezeDefinition(Document):
    study_id: Text
    revision: Annotated[int, Field(gt=0)]
    mode: Literal["pilot", "final"]
    catalog: Catalog
    splits: SplitManifest
    cases: tuple[TestCaseDefinition, ...]
    models: tuple[FrozenFamilyModel, ...]
    selection_evidence: tuple[SelectionEvidence, ...]
    decisions: tuple[ExperimentalDecision, ...]
    files: tuple[FrozenInput, ...]
    environment: tuple[EnvironmentPin, ...]
    code_revision: Text
    evaluation: EvaluationConfig
    cost_protocol: CostProtocol

    @model_validator(mode="after")
    def metadata(self) -> Self:
        if tuple(m.family for m in self.models) != FAMILIES:
            raise ValueError("freeze requires all five families in canonical order")
        if {d.name for d in self.decisions} != set(DECISIONS) or len(self.decisions) != len(
            DECISIONS
        ):
            raise ValueError("freeze requires the twelve explicit experimental decisions")
        if self.evaluation.mode != "pilot" or self.evaluation.freeze_sha256 is not None:
            raise ValueError(
                "pre-freeze evaluation protocol must not contain a circular freeze hash"
            )
        for values in (
            [c.case_id for c in self.cases],
            [e.candidate.candidate_id for e in self.selection_evidence],
            [f.name for f in self.files],
            [p.package for p in self.environment],
        ):
            if len(values) != len(set(values)):
                raise ValueError(
                    "freeze case, evidence, input and environment names must be unique"
                )
        locations: dict[str, tuple[str, int]] = {}
        for item in self.files:
            location = str(Path(item.path)).casefold()
            identity = (item.sha256, item.size_bytes)
            if location in locations and locations[location] != identity:
                raise ValueError("one frozen path cannot declare different contents")
            locations[location] = identity
        return self


class FreezeCount(Document):
    family: ef.Family
    partition: Partition
    scenarios: Annotated[int, Field(ge=0)]
    cases: Annotated[int, Field(ge=0)]
    confirmed: Annotated[int, Field(ge=0)]
    pending: Annotated[int, Field(ge=0)]
    disagreement: Annotated[int, Field(ge=0)]
    not_evaluable: Annotated[int, Field(ge=0)]

    @model_validator(mode="after")
    def totals(self) -> Self:
        if self.cases != self.confirmed + self.pending + self.disagreement + self.not_evaluable:
            raise ValueError("case availability counts must close exactly")
        return self


class FreezeAudit(Document):
    definition_sha256: Digest
    ready: bool
    blockers: tuple[Text, ...]
    integrity_blockers: tuple[Text, ...]
    counts: tuple[FreezeCount, ...]

    @model_validator(mode="after")
    def blockers_consistent(self) -> Self:
        if not set(self.integrity_blockers) <= set(self.blockers):
            raise ValueError("integrity blockers must also be listed as blockers")
        for values in (self.blockers, self.integrity_blockers):
            if len(values) != len(set(values)):
                raise ValueError("audit blockers must be unique")
        if self.ready and self.integrity_blockers:
            raise ValueError("an integrity failure cannot be ready")
        return self

    @property
    def technical_ready(self) -> bool:
        return not self.integrity_blockers

    @property
    def scientific_ready(self) -> bool:
        return not self.blockers


class ModelBinding(Document):
    family: ef.Family
    profile_sha256: Digest
    training_sha256: Digest | None
    calibration_sha256: Digest | None
    audit_sha256: Digest | None
    bundle_sha256: Digest | None


def _bindings(definition: FreezeDefinition) -> tuple[ModelBinding, ...]:
    return tuple(
        ModelBinding(
            family=m.family,
            profile_sha256=ef.profile_spec_fingerprint(m.profile),
            training_sha256=digest(m.training) if m.training is not None else None,
            calibration_sha256=digest(m.calibration) if m.calibration is not None else None,
            audit_sha256=digest(m.audit) if m.audit is not None else None,
            bundle_sha256=ef.detector_fingerprint(m.bundle) if m.bundle is not None else None,
        )
        for m in definition.models
    )


def _counts(definition: FreezeDefinition) -> tuple[FreezeCount, ...]:
    partitions = {a.scenario_id: a.partition for a in definition.splits.assignments}
    scenarios = {s.scenario_id: s for s in definition.catalog.scenarios}
    result = []
    for family in FAMILIES:
        for partition in _PARTITIONS:
            selected = {
                s.scenario_id
                for s in scenarios.values()
                if s.family == family and partitions.get(s.scenario_id) == partition
            }
            cases = [c for c in definition.cases if c.scenario_id in selected]
            states = [c.oracle.status if c.oracle is not None else "pending" for c in cases]
            result.append(
                FreezeCount(
                    family=family,
                    partition=partition,
                    scenarios=len(selected),
                    cases=len(cases),
                    confirmed=states.count("confirmed"),
                    pending=states.count("pending"),
                    disagreement=states.count("disagreement"),
                    not_evaluable=states.count("not_evaluable"),
                )
            )
    return tuple(result)


def _scientific_blockers(definition: FreezeDefinition) -> list[str]:
    blockers = []
    if definition.catalog.synthetic:
        blockers.append("scientific:synthetic_catalog")
    blockers.extend(
        "scientific:pending_decision:" + d.name
        for d in definition.decisions
        if d.status == "pending"
    )
    roles = {f.role for f in definition.files}
    blockers.extend(
        "scientific:missing_file_role:" + role for role in _FILE_ROLES if role not in roles
    )
    if not re.fullmatch(r"[0-9a-f]{40}|[0-9a-f]{64}", definition.code_revision):
        blockers.append("scientific:unfixed_code_revision")
    required = {"python", "equiframe", "equiframe-benchmark", "pyarrow", "pydantic", "tzdata"}
    required.update(c.pipeline.execution.engine for c in definition.cases)
    if any(m.bundle is not None and m.bundle.fit.m.state == "fitted" for m in definition.models):
        required.update(("scikit-learn", "numpy"))
    packages = {p.package for p in definition.environment}
    blockers.extend("scientific:missing_environment_pin:" + p for p in sorted(required - packages))
    if not any(m.bundle is not None and m.bundle.m.state == "ready" for m in definition.models):
        blockers.append("scientific:no_supported_detector_bundle")
    if not any(c.oracle is not None and c.oracle.status == "confirmed" for c in definition.cases):
        blockers.append("scientific:no_confirmed_test_case")
    return blockers


def _evaluation_scope(definition: FreezeDefinition) -> None:
    expected = definition.evaluation.expected_families
    if definition.mode == "final" and expected != FAMILIES:
        raise ValueError("final protocol must declare all five families in canonical order")
    families = {s.family for s in definition.catalog.scenarios} | {
        c.pipeline.execution.contract.family for c in definition.cases
    }
    if not families <= set(expected):
        raise ValueError("evaluation family scope omits declared catalog or case families")
    migrations = definition.evaluation.expected_migrations
    if migrations and not {c.migration for c in definition.cases} <= set(migrations):
        raise ValueError("evaluation migration scope omits declared case migrations")


class FreezeManifest(Document):
    definition: FreezeDefinition
    definition_sha256: Digest
    evaluation_protocol_sha256: Digest
    cost_protocol_sha256: Digest
    catalog_sha256: Digest
    splits_sha256: Digest
    model_bindings: tuple[ModelBinding, ...]
    audit: FreezeAudit

    @model_validator(mode="after")
    def closed(self) -> Self:
        _evaluation_scope(self.definition)
        expected = (
            digest(self.definition),
            evaluation_protocol_sha256(self.definition.evaluation),
            digest(self.definition.cost_protocol),
            digest(self.definition.catalog),
            digest(self.definition.splits),
            _bindings(self.definition),
        )
        actual = (
            self.definition_sha256,
            self.evaluation_protocol_sha256,
            self.cost_protocol_sha256,
            self.catalog_sha256,
            self.splits_sha256,
            self.model_bindings,
        )
        if actual != expected or self.audit.definition_sha256 != self.definition_sha256:
            raise ValueError("freeze fingerprints and model bindings must close exactly")
        if self.audit.counts != _counts(self.definition):
            raise ValueError("freeze counts must describe the actual definitions")
        expected_blockers = tuple(sorted(set(_scientific_blockers(self.definition))))
        if self.audit.blockers != expected_blockers:
            raise ValueError("published freeze blockers must describe its exact configuration")
        ready = (
            self.audit.technical_ready
            if self.definition.mode == "pilot"
            else self.audit.scientific_ready
        )
        if self.audit.ready != ready or not ready:
            raise ValueError("published freeze must satisfy its explicit pilot/final gate")
        return self


class _PhysicalEvidence:
    def __init__(self) -> None:
        self.identities: dict[str, tuple[str, int, str]] = {}
        self.paths: dict[Path, tuple[str, int]] = {}
        self.tables: set[tuple[str, str, int, str]] = set()

    def artifact(self, ref: ef.ArtifactRef, *, table: bool = True) -> None:
        if ref.sha256 is None or ref.size_bytes is None:
            raise ValueError("physical evidence requires a SHA-256 and byte size")
        path = _plain_path(local_path(ref))
        identity = (ref.sha256, ref.size_bytes, ref.format)
        previous = self.identities.get(ref.uri)
        if previous is not None and previous != identity:
            raise ValueError("one evidence URI declares different contents or formats")
        self.identities[ref.uri] = identity
        if self.paths.get(path) != identity[:2]:
            if _stream_file(path, ref.size_bytes) != identity[:2]:
                raise ValueError("physical evidence SHA-256 or byte size mismatch")
            self.paths[path] = identity[:2]
        key = (ref.uri, *identity)
        if table and key not in self.tables:
            ef.read_table(ref)
            self.tables.add(key)

    def frozen_input(self, item: FrozenInput) -> None:
        if not Path(item.path).is_absolute():
            raise ValueError(
                "foreign frozen paths must be resolved explicitly before physical audit"
            )
        path = _plain_path(Path(item.path))
        identity = (item.sha256, item.size_bytes)
        if _stream_file(path, item.size_bytes) != identity:
            raise ValueError("frozen input SHA-256 or byte size mismatch")
        if path in self.paths and self.paths[path] != identity:
            raise ValueError("frozen input and table reference disagree")
        self.paths[path] = identity

    def recheck(self) -> None:
        for path, identity in self.paths.items():
            if _stream_file(path, identity[1]) != identity:
                raise ValueError("source evidence changed during freeze verification")


def _physical_table(table: ef.TableArtifact, evidence: _PhysicalEvidence) -> None:
    import pyarrow as pa
    import pyarrow.compute as pc

    for ref, columns in ((table.data, table.columns), (table.index, table.index_columns)):
        if ref is None:
            continue
        evidence.artifact(ref)
        actual = ef.read_table(ref)
        if actual.num_rows != table.row_count or actual.column_names != [c.name for c in columns]:
            raise ValueError("captured table row or column metadata differs from its bytes")
        for index, column in enumerate(columns):
            values = actual.column(index)
            nan_count = (
                pc.sum(pc.fill_null(pc.is_nan(values), False)).as_py()
                if pa.types.is_floating(values.type)
                else 0
            )
            if (str(values.type), values.null_count, nan_count or 0) != (
                column.arrow_type,
                column.null_count,
                column.nan_count,
            ):
                raise ValueError("captured table type, NULL or NaN metadata differs from its bytes")


def _verify_oracle(
    scenario: Scenario,
    candidate: Candidate,
    oracle: OracleResult,
    evidence: _PhysicalEvidence,
    work_dir: Path,
) -> None:
    if oracle.scenario_sha256 != digest(scenario) or oracle.candidate_sha256 != digest(candidate):
        raise ValueError("oracle does not bind the exact scenario and candidate")
    if oracle.candidate_kind != candidate.kind:
        raise ValueError("oracle candidate kind differs")
    validate_packet(scenario, candidate, oracle.packet)
    if oracle.assignment is not None:
        validate_assignment(scenario, candidate, oracle.packet, oracle.assignment)
    for item in oracle.packet.inputs:
        evidence.artifact(item.artifact)
    for ref in (oracle.packet.expected, oracle.packet.candidate):
        evidence.artifact(ref)
    for source in (oracle.comparison.left, oracle.comparison.right):
        if source is None:
            continue
        evidence.artifact(source.data)
        if source.table is not None:
            if not same_content(source.data, source.table.data):
                raise ValueError("comparison table does not bind its source artifact")
            _physical_table(source.table, evidence)
        if source.execution is not None:
            execution = source.execution
            if (
                execution.state != "completed"
                or execution.output is None
                or not same_content(source.data, execution.output.data)
            ):
                raise ValueError("comparison execution does not bind its source artifact")
            for table in (*execution.inputs, execution.output):
                _physical_table(table, evidence)
    evidence.artifact(oracle.comparison.differences, table=False)
    recorded = tuple(ef.iter_differences(oracle.comparison.differences))
    if len(recorded) != oracle.comparison.counts.difference_records:
        raise ValueError("oracle difference inventory disagrees with recorded counts")
    if oracle.status == "confirmed":
        observed = ef.compare(
            oracle.packet.candidate,
            oracle.packet.expected,
            contract=scenario.comparison.contract,
            policy=scenario.comparison.policy,
            options=oracle.comparison.options,
            reference="expected",
            work_dir=work_dir,
        )
        if (
            observed.state,
            observed.complete,
            observed.counts,
            observed.strategy,
            observed.selected_key,
        ) != (
            oracle.comparison.state,
            oracle.comparison.complete,
            oracle.comparison.counts,
            oracle.comparison.strategy,
            oracle.comparison.selected_key,
        ) or tuple(ef.iter_differences(observed.differences)) != recorded:
            raise ValueError("confirmed oracle comparison differs from captured logical contents")


def _verify_selection_evidence(
    item: SelectionEvidence, scenario: Scenario, evidence: _PhysicalEvidence, work_dir: Path
) -> None:
    validate_candidate(scenario, item.candidate)
    _verify_oracle(scenario, item.candidate, item.oracle, evidence, work_dir)
    execution, profile = item.execution, item.profile
    if execution.state != "completed" or execution.output is None:
        raise ValueError("selection requires a completed captured execution")
    if (
        execution.output.data != item.candidate.output
        or execution.implementation_version != item.candidate.implementation
    ):
        raise ValueError("selection execution differs from its candidate")
    if execution.plan.contract != scenario.comparison.contract:
        raise ValueError("selection execution contract differs from scenario")
    sources = {t.name: t.data for t in execution.inputs}
    if set(sources) != {i.name for i in scenario.inputs} or any(
        not same_content(i.artifact, sources[i.name]) for i in scenario.inputs
    ):
        raise ValueError("selection execution inputs differ from scenario")
    for table in (*execution.inputs, execution.output):
        _physical_table(table, evidence)
    artifacts = tuple(
        ref
        for table in (*execution.inputs, execution.output)
        for ref in (table.data, *((table.index,) if table.index else ()))
    )
    if (
        profile.metadata.execution_sha256 != digest(execution)
        or profile.metadata.execution_id != execution.execution_id
        or profile.metadata.run_id != execution.run_id
        or profile.metadata.contract_sha256 != execution.contract_sha256
        or profile.metadata.artifacts != artifacts
        or profile.vector.spec_sha256 != scenario.features_sha256
        or profile.vector.spec.family != scenario.family
        or not profile.complete
    ):
        raise ValueError("selection profile lineage or completeness differs")
    observed = ef.profile_execution(
        execution,
        spec=profile.vector.spec,
        options=profile.options,
        conversions=profile.metadata.conversion_receipts,
        work_dir=work_dir,
    )
    if observed.vector != profile.vector or observed.complete != profile.complete:
        raise ValueError("profile vector differs from captured execution contents")


def _selected(
    model: FrozenFamilyModel, definition: FreezeDefinition, *, calibration: bool
) -> TrainingSelection | CalibrationSelection | None:
    selection = model.calibration if calibration else model.training
    if selection is None:
        return None
    evidence = {e.candidate.candidate_id: e for e in definition.selection_evidence}
    names = [r.candidate_id for r in selection.manifest.records]
    if any(name not in evidence for name in names):
        raise ValueError("selection manifest refers to absent captured evidence")
    supplied = [evidence[name] for name in names]
    if any(e.profile.vector.spec != model.profile for e in supplied):
        raise ValueError("selection feature specification differs from frozen family")
    selector = select_normal_calibration if calibration else select_normal_training
    actual = selector(
        definition.catalog,
        definition.splits,
        candidates={e.candidate.candidate_id: e.candidate for e in supplied},
        oracles={e.candidate.candidate_id: e.oracle for e in supplied},
        profiles={e.candidate.candidate_id: e.profile for e in supplied},
        executions={e.candidate.candidate_id: e.execution for e in supplied},
    )
    if actual != selection:
        raise ValueError("selection manifest or vectors differ from reselected reviewed evidence")
    return actual


def _verify_model(model: FrozenFamilyModel, definition: FreezeDefinition) -> None:
    _selected(model, definition, calibration=False)
    _selected(model, definition, calibration=True)
    if model.audit is not None:
        if not (model.training is not None and model.calibration is not None):
            raise AssertionError("Internal invariant check failed.")
        actual_audit = audit_detector_selections(
            model.training,
            model.calibration,
            min_training_groups=model.audit.min_training_groups,
            min_calibration_groups=model.audit.min_calibration_groups,
            rationale=model.audit.rationale,
        )
        if actual_audit != model.audit:
            raise ValueError("group support audit differs from actual selections")
    if model.bundle is None:
        return
    if not (
        model.training is not None and model.calibration is not None and model.audit is not None
    ):
        raise AssertionError("Internal invariant check failed.")
    if model.audit.state != "eligible":
        raise ValueError("a detector bundle cannot bypass insufficient group support")
    fit = model.bundle.fit
    if fit.preprocessor.spec != model.profile:
        raise ValueError("frozen preprocessor has a different feature specification")
    preprocessor = ef.fit_preprocessor(
        model.training.training, spec=model.profile, empty_policy=fit.preprocessor.empty_policy
    )
    if preprocessor != fit.preprocessor:
        raise ValueError("frozen preprocessor differs from actual training selection")
    matrix = (
        ef.transform_profiles(preprocessor, model.training.training.profiles)
        if preprocessor.state == "ready"
        else None
    )
    fingerprint = profile_digest(matrix.model_dump(mode="json")) if matrix is not None else None
    if fingerprint != fit.training_matrix_sha256:
        raise ValueError("frozen training matrix fingerprint differs")
    if matrix is not None and fit.b.state == "fitted":
        # MAD is reproducible directly from the frozen matrix, without fitting ML.
        def median(values: tuple[float, ...]) -> float:
            ordered = sorted(values)
            middle = len(ordered) // 2
            return (
                ordered[middle]
                if len(ordered) % 2
                else float((Fraction(ordered[middle - 1]) + Fraction(ordered[middle])) / 2)
            )

        columns = tuple(zip(*matrix.values, strict=True))
        medians = tuple(median(values) for values in columns)
        deviations = tuple(
            median(tuple(abs(value - center) for value in values))
            for center, values in zip(medians, columns, strict=True)
        )
        if medians != fit.b.medians or deviations != fit.b.deviations:
            raise ValueError("MAD parameters differ from the frozen training matrix")
    alpha = next(d for d in definition.decisions if d.name == "alpha")
    if alpha.value is not None and (
        alpha.value != model.bundle.m.alpha or alpha.value != model.bundle.b.alpha
    ):
        raise ValueError("detector alpha differs from the frozen experimental decision")
    actual_bundle = ef.calibrate_detectors(
        fit, model.calibration.calibration, alpha=model.bundle.m.alpha
    )
    if actual_bundle != model.bundle:
        raise ValueError("detector calibration differs from frozen fit and separate selection")


def _environment(pin: EnvironmentPin) -> None:
    if pin.package == "python":
        actual = platform.python_version()
    elif pin.package == "equiframe":
        actual = ef.__version__
    elif pin.package == "equiframe-benchmark":
        from equiframe_benchmark import __version__

        actual = __version__
    else:
        try:
            actual = version(pin.package)
        except PackageNotFoundError as exc:
            raise ValueError("declared environment package is unavailable") from exc
    if pin.version != actual:
        raise ValueError("declared environment pin differs from current runtime")


def audit_freeze(
    definition: FreezeDefinition,
    *,
    rule_registry: ef.RuleRegistry | None = None,
    work_dir: Path | None = None,
) -> FreezeAudit:
    """Check actual evidence and support without executing ETL or fitting models.

    Verification creates disposable comparison/profile evidence in a private folder.
    Unconfirmed cases remain unconfirmed; reviewer identities are not authenticated.
    """
    definition = FreezeDefinition.model_validate(definition)
    integrity: list[str] = []
    evidence = _PhysicalEvidence()

    def check(name: str, action: Callable[[], None]) -> None:
        try:
            action()
        except (ValueError, OSError, ef.EquiFrameError) as exc:
            integrity.append("integrity:" + name + ":" + type(exc).__name__)

    check("splits", lambda: validate_splits(definition.catalog, definition.splits))
    check("evaluation_scope", partial(_evaluation_scope, definition))
    for frozen_file in definition.files:
        check(
            "input:" + frozen_file.name,
            partial(evidence.frozen_input, frozen_file),
        )
    for pin in definition.environment:
        check("environment:" + pin.package, partial(_environment, pin))
    registry = rule_registry if rule_registry is not None else ef.default_rule_registry()
    if work_dir is not None:
        _plain_path(work_dir, directory=True)
    with TemporaryDirectory(prefix="equiframe-freeze-", dir=work_dir) as scratch:
        verification = Path(scratch)
        scenarios = {s.scenario_id: s for s in definition.catalog.scenarios}
        hashes = {digest(s): s for s in definition.catalog.scenarios}
        assignments = {a.scenario_id: a for a in definition.splits.assignments}
        models = {m.family: m for m in definition.models}
        known_candidates: dict[str, Candidate] = {}
        for scenario in definition.catalog.scenarios:

            def verify_scenario(scenario: Scenario = scenario) -> None:
                for ref in (*[i.artifact for i in scenario.inputs], scenario.expected):
                    evidence.artifact(ref)
                if scenario.features_sha256 != ef.profile_spec_fingerprint(
                    models[scenario.family].profile
                ):
                    raise ValueError("scenario features differ from frozen family")
                options = (
                    ef.RuleOptions(),
                    *(
                        c.pipeline.rule_options
                        for c in definition.cases
                        if c.pipeline.execution.contract.family == scenario.family
                    ),
                )
                if not any(
                    ef.rule_set_fingerprint(scenario.comparison.contract, registry, option)
                    == scenario.rules_sha256
                    for option in options
                ):
                    raise ValueError(
                        "scenario rules differ from frozen registry and declared options"
                    )

            check("scenario:" + scenario.scenario_id, verify_scenario)
        for case in definition.cases:

            def verify_case(case: TestCaseDefinition = case) -> None:
                scenario = scenarios.get(case.scenario_id)
                assignment = assignments.get(case.scenario_id)
                if scenario is None or assignment is None or assignment.partition != "test":
                    raise ValueError("only declared held-out test scenarios may become cases")
                validate_candidate(scenario, case.candidate)
                prior = known_candidates.get(case.candidate.candidate_id)
                if prior is not None and prior != case.candidate:
                    raise ValueError("one candidate ID cannot bind different evidence")
                known_candidates[case.candidate.candidate_id] = case.candidate
                evidence.artifact(case.candidate.output)
                if (
                    case.pipeline.execution.contract != scenario.comparison.contract
                    or case.pipeline.comparison_policy != scenario.comparison.policy
                ):
                    raise ValueError("case contract or comparison policy differs from scenario")
                if case.pipeline.profile != models[scenario.family].profile:
                    raise ValueError("case feature definition differs from frozen family")
                actual_rules = ef.rule_set_fingerprint(
                    scenario.comparison.contract, registry, case.pipeline.rule_options
                )
                if actual_rules != scenario.rules_sha256:
                    raise ValueError(
                        "case rule options differ from the rules fixed before its candidate"
                    )
                if case.pipeline.comparison_reference != "expected":
                    raise ValueError("experimental cases require independent expected reference")
                if case.oracle is not None:
                    _verify_oracle(scenario, case.candidate, case.oracle, evidence, verification)

            check("case:" + case.case_id, verify_case)
        for item in definition.selection_evidence:

            def verify_item(item: SelectionEvidence = item) -> None:
                scenario = hashes.get(item.candidate.scenario_sha256)
                if scenario is None:
                    raise ValueError("selection candidate refers to an unknown scenario")
                prior = known_candidates.get(item.candidate.candidate_id)
                if prior is not None and prior != item.candidate:
                    raise ValueError("one candidate ID cannot bind different evidence")
                known_candidates[item.candidate.candidate_id] = item.candidate
                _verify_selection_evidence(item, scenario, evidence, verification)

            check("selection:" + item.candidate.candidate_id, verify_item)
        for model in definition.models:
            check("model:" + model.family, partial(_verify_model, model, definition))
        check("sources_unchanged", evidence.recheck)
    blockers = tuple(sorted(set((*_scientific_blockers(definition), *integrity))))
    return FreezeAudit(
        definition_sha256=digest(definition),
        ready=not integrity if definition.mode == "pilot" else not blockers,
        blockers=blockers,
        integrity_blockers=tuple(sorted(set(integrity))),
        counts=_counts(definition),
    )


def create_freeze(
    definition: FreezeDefinition,
    *,
    rule_registry: ef.RuleRegistry | None = None,
    work_dir: Path | None = None,
) -> FreezeManifest:
    """Return a closed seal only after its explicit technical/scientific gate passes."""
    definition = FreezeDefinition.model_validate(definition)
    audit = audit_freeze(definition, rule_registry=rule_registry, work_dir=work_dir)
    if not audit.ready:
        raise ValueError("freeze is blocked: " + "; ".join(audit.blockers))
    return FreezeManifest(
        definition=definition,
        definition_sha256=digest(definition),
        evaluation_protocol_sha256=evaluation_protocol_sha256(definition.evaluation),
        cost_protocol_sha256=digest(definition.cost_protocol),
        catalog_sha256=digest(definition.catalog),
        splits_sha256=digest(definition.splits),
        model_bindings=_bindings(definition),
        audit=audit,
    )


def read_freeze(
    path: Path,
    *,
    expected_sha256: str | None = None,
    rule_registry: ef.RuleRegistry | None = None,
    work_dir: Path | None = None,
    max_bytes: int = 64 * 1024**2,
) -> FreezeManifest:
    """Recheck a seal, its physical sources and exact audit; never execute stored code."""
    if type(max_bytes) is not int or max_bytes < 1:
        raise ValueError("freeze JSON byte budget must be a positive integer")
    manifest, checksum = _bounded_json(FreezeManifest, path, max_bytes)
    if expected_sha256 is not None and checksum != expected_sha256:
        raise ValueError("freeze document SHA-256 mismatch")
    observed = audit_freeze(manifest.definition, rule_registry=rule_registry, work_dir=work_dir)
    if _stream_file(path, max_bytes)[0] != checksum:
        raise ValueError("freeze document changed during verification")
    if observed != manifest.audit or not observed.ready:
        raise ValueError("freeze verification no longer matches its sealed audit")
    return manifest
