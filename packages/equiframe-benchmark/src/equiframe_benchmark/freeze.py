class FrozenInput(Document):
    name: Text
    role: Text
    path: Text
    sha256: Digest
    size_bytes: Annotated[int, Field(ge=0)]

    @model_validator(mode="after")
    def local(self) -> Self:
        windows, posix = PureWindowsPath(self.path), PurePosixPath(self.path)
        if not (windows.is_absolute() or posix.is_absolute()) or windows.drive.startswith("\\\\"):
            raise ValueError("frozen inputs require explicit absolute local paths")
        return self


class EnvironmentPin(Document):
    package: Text
    version: Text

    @model_validator(mode="after")
    def package_name(self) -> Self:
        if not re.fullmatch(r"[a-z0-9]+(?:-[a-z0-9]+)*", self.package):
            raise ValueError("environment packages require canonical lowercase names")
        return self


class ExperimentalDecision(Document):
    name: DecisionName
    status: Literal["resolved", "pending"]
    value: Text | None
    rationale: Text

    @model_validator(mode="after")
    def resolution(self) -> Self:
        if (self.status == "resolved") != (self.value is not None):
            raise ValueError("resolved decisions require values; pending decisions have none")
        if (
            self.name == "alpha"
            and self.value is not None
            and (
                not re.fullmatch(r"0\.[0-9]{1,18}", self.value) or not 0 < Fraction(self.value) < 1
            )
        ):
            raise ValueError("alpha must be an explicit decimal probability")
        return self


