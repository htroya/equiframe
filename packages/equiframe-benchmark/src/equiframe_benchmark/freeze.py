class FrozenFamilyModel(Document):
    family: ef.Family
    profile: ef.ProfileSpec
    training: TrainingSelection | None = None
    calibration: CalibrationSelection | None = None
    audit: DetectorSelectionAudit | None = None
    bundle: ef.DetectorBundle | None = None
    reason: Text | None = None

    @model_validator(mode="after")
    def support(self) -> Self:
        if self.profile.family != self.family:
            raise ValueError("family model and profile must agree")
        if self.bundle is None and self.reason is None:
            raise ValueError("an unsupported family requires an explicit reason")
        if self.bundle is not None and (
            self.training is None or self.calibration is None or self.audit is None
        ):
            raise ValueError("a bundle requires full training, calibration and support evidence")
        if self.audit is not None and (self.training is None or self.calibration is None):
            raise ValueError("selection audit requires both selections")
        return self


