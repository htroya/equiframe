"""Build an immutable first-use kit from current source and the exact built wheel.

No dependencies are resolved and no wheel is rebuilt here. Dependency versions
and hashes come only from uv.lock. This folder can be zipped and delivered
privately; it contains no virtualenv, user data or acceptance claim.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import runpy
import shutil
import stat
import tomllib
import zipfile
from email.parser import BytesParser
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
ROOTS = ("pandas", "duckdb", "pyarrow", "pydantic", "typer", "tzdata", "pytest")
DOCUMENTS = (
    "README.md",
    "INTERPRETATION.md",
    "OBSERVATION.md",
    "requirements.lock",
    "verify_kit.py",
)
RECIPES = (
    "refactor_comparison.py",
    "migrate_duckdb_recipe.py",
    "assertion_ci.py",
    "test_assertion_recipe.py",
)


def file_record(path: Path) -> dict[str, Any]:
    if not stat.S_ISREG(path.lstat().st_mode):
        raise ValueError("source must contain only regular files: " + str(path))
    data = path.read_bytes()
    return {"sha256": hashlib.sha256(data).hexdigest(), "size_bytes": len(data)}


def canonical_hash(value: object) -> str:
    return hashlib.sha256(
        json.dumps(value, sort_keys=True, separators=(",", ":")).encode("utf-8")
    ).hexdigest()


def locked_requirements(lock: Path) -> str:
    """Export the cross-platform union of the recipe dependency closure.

    Conditional dependencies are deliberately pinned too (e.g. colorama), so
    Python 3.12 Windows and Linux use one file. Reject ambiguous resolutions
    rather than silently selecting a version. Installation requires wheels.
    """
    document = tomllib.loads(lock.read_text("utf-8"))
    packages: dict[str, Any] = {}
    for package in document["package"]:
        name = package["name"]
        if name in packages:
            raise ValueError("multiple locked resolutions need explicit first-use support")
        packages[name] = package
    selected = set()
    pending = list(ROOTS)
    while pending:
        name = pending.pop()
        if name in selected:
            continue
        if name not in packages:
            raise ValueError("missing locked recipe dependency: " + name)
        selected.add(name)
        pending.extend(dependency["name"] for dependency in packages[name].get("dependencies", []))
    lines = [
        "# Generated by tools/build_first_use_kit.py from uv.lock; do not edit by hand.",
        "# Python 3.12; cross-platform union closure; install with --require-hashes.",
        "# Roots: " + ", ".join(ROOTS),
        "# Regenerate intentionally with --write-requirements; never resolves new versions.",
        "",
    ]
    for name in sorted(selected):
        package = packages[name]
        if set(package.get("source", {})) != {"registry"}:
            raise ValueError("first-use dependencies must be registry artifacts")
        artifacts = list(package.get("wheels", []))
        if "sdist" in package:
            artifacts.append(package["sdist"])
        hashes = sorted({artifact["hash"] for artifact in artifacts})
        if not hashes or any(re.fullmatch(r"sha256:[0-9a-f]{64}", h) is None for h in hashes):
            raise ValueError("dependency has no valid locked SHA-256 artifacts")
        lines.append(name + "==" + package["version"] + " \\")
        lines.extend(
            "    --hash=" + digest + (" \\" if index < len(hashes) - 1 else "")
            for index, digest in enumerate(hashes)
        )
    return "\n".join(lines) + "\n"


def verify_wheel_source(wheel: Path, package: Path, version: str) -> dict[str, dict[str, Any]]:
    """Reject stale runtime payloads even when their version string still matches."""
    runtime = package / "src" / "equiframe"
    source = {}
    for path in sorted(runtime.rglob("*")):
        relative = path.relative_to(package / "src").as_posix()
        if "__pycache__" in path.parts or path.suffix in {".pyc", ".pyo"}:
            continue
        if path.is_symlink():
            raise ValueError("runtime source cannot contain symlinks")
        if path.is_file():
            source[relative] = file_record(path)
    config = tomllib.loads((package / "pyproject.toml").read_text("utf-8"))
    mapping = (
        config.get("tool", {})
        .get("hatch", {})
        .get("build", {})
        .get("targets", {})
        .get("wheel", {})
        .get("force-include", {})
    )
    if mapping:
        if mapping != {"docs": "equiframe/docs"}:
            raise ValueError("unsupported wheel force-include mapping")
        handbook = package / "docs"
        if handbook.is_symlink() or not handbook.is_dir():
            raise ValueError("packaged handbook source is absent or linked")
        documents = {}
        for path in sorted(handbook.rglob("*")):
            if path.is_symlink():
                raise ValueError("packaged handbook cannot contain symlinks")
            if path.is_file():
                key = "equiframe/docs/" + path.relative_to(handbook).as_posix()
                if key in source:
                    raise ValueError("packaged handbook shadows runtime payload")
                documents[key] = file_record(path)
        if not documents:
            raise ValueError("packaged handbook is empty")
        source.update(documents)
    if not source:
        raise ValueError("runtime source payload is empty")
    file_record(wheel)
    with zipfile.ZipFile(wheel) as archive:
        names = archive.namelist()
        if len(names) != len(set(names)):
            raise ValueError("wheel contains duplicate entries")
        payload = {
            name for name in names if name.startswith("equiframe/") and not name.endswith("/")
        }
        if payload != set(source):
            raise ValueError("wheel runtime inventory differs from current source; rebuild first")
        for name, record in source.items():
            data = archive.read(name)
            if (
                len(data) != record["size_bytes"]
                or hashlib.sha256(data).hexdigest() != record["sha256"]
            ):
                raise ValueError("wheel runtime bytes differ from current source; rebuild first")
        metadata_paths = [name for name in names if name.endswith(".dist-info/METADATA")]
        if len(metadata_paths) != 1:
            raise ValueError("wheel must identify exactly one distribution")
        metadata = BytesParser().parsebytes(archive.read(metadata_paths[0]))
        if metadata["Name"] != "equiframe" or metadata["Version"] != version:
            raise ValueError("built wheel metadata does not match this candidate")
    return source


def build_kit(output: Path, *, package: Path = ROOT) -> dict[str, Any]:
    package = package.resolve()
    requirements = locked_requirements(package / "uv.lock")
    expected = package / "examples" / "first_use" / "requirements.lock"
    if expected.read_text("utf-8") != requirements:
        raise ValueError("requirements.lock is stale; regenerate from the unchanged uv.lock")
    version = tomllib.loads((package / "pyproject.toml").read_text("utf-8"))["project"]["version"]
    wheels = tuple((package / "dist").glob(f"equiframe-{version}-*.whl"))
    if len(wheels) != 1:
        raise ValueError("build exactly one candidate wheel in dist/ first")
    wheel = wheels[0]
    runtime = verify_wheel_source(wheel, package, version)
    payload = {name: package / "examples" / "first_use" / name for name in DOCUMENTS}
    payload.update({name: package / "examples" / name for name in RECIPES})
    # Validate every source before creating output. Existing paths are never overwritten.
    sources = {path.relative_to(package).as_posix(): file_record(path) for path in payload.values()}
    sources["uv.lock"] = file_record(package / "uv.lock")
    sources["pyproject.toml"] = file_record(package / "pyproject.toml")
    output.mkdir(parents=True, exist_ok=False)
    for name, path in payload.items():
        shutil.copyfile(path, output / name)
    (output / "wheels").mkdir()
    wheel_name = "wheels/" + wheel.name
    shutil.copyfile(wheel, output / wheel_name)
    manifest = {
        "schema": "equiframe-first-use-kit-1",
        "package": {"name": "equiframe", "version": version, "python": ">=3.12,<3.13"},
        "wheel": wheel_name,
        "dependency_roots": list(ROOTS),
        "source_payload": {"files": sources, "sha256": canonical_hash(sources)},
        "runtime_payload": {"files": runtime, "sha256": canonical_hash(runtime)},
        "files": {name: file_record(output / name) for name in sorted([*payload, wheel_name])},
        "scope": "Byte integrity and synthetic recipes; no human acceptance or public release",
    }
    (output / "manifest.json").write_text(
        json.dumps(manifest, indent=2, sort_keys=True) + "\n", "utf-8"
    )
    runpy.run_path(str(package / "examples" / "first_use" / "verify_kit.py"))["verify_kit"](output)
    return manifest


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, help="fresh kit directory; never overwritten")
    parser.add_argument(
        "--write-requirements", action="store_true", help="export existing lock only"
    )
    args = parser.parse_args()
    if args.write_requirements:
        (ROOT / "examples" / "first_use" / "requirements.lock").write_text(
            locked_requirements(ROOT / "uv.lock"), "utf-8"
        )
    if args.output is not None:
        manifest = build_kit(args.output)
        print("First-use kit built: " + str(args.output.resolve()))
        print("Exact wheel SHA-256: " + manifest["files"][manifest["wheel"]]["sha256"])
    elif not args.write_requirements:
        parser.error("provide --output or --write-requirements")


if __name__ == "__main__":
    main()
