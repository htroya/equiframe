"""Exercise public declaration aliases against frozen independent literal values.

These receipts establish type admission and constant identity only. They do not
establish detector decisions, native engines, complete public function behavior,
scientific results or additional coverage from replays.
"""

from __future__ import annotations

import argparse
import importlib.util
import json
import platform
import sys
from pathlib import Path

SPEC = importlib.util.spec_from_file_location(
    "option_boundary_followup", Path(__file__).with_name("option_boundary_followup.py")
)
if SPEC is None or SPEC.loader is None:
    raise ValueError("Existing coverage verifier unavailable")
boundary = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(boundary)
op = boundary.op

# Transcribed from A13 declaration source before execution, not generated by
# calling TypeAdapter, a detector, or any SDK serialization operation.
LITERALS = {
    "CheckState": ("satisfied", "violated", "not_applicable", "not_evaluable"),
    "ComparisonState": ("equivalent", "different", "not_evaluable"),
    "DecisionState": ("alert", "no_alert", "not_evaluable"),
    "ExecutionState": (
        "completed",
        "invalid_input",
        "failed",
        "timeout",
        "resource_exhausted",
        "cancelled",
    ),
    "Family": ("nulls_types", "joins", "duplicates_order", "aggregations", "dates"),
    "FeatureState": ("available", "undefined", "not_applicable", "not_evaluable"),
    "FitState": ("ready", "not_estimable", "incompatible"),
    "JobState": ("queued", "running", "succeeded", "failed", "cancelled"),
    "Multiplicity": ("preserve", "distinct"),
    "OracleState": ("correct", "divergent", "pending", "not_evaluable"),
    "ProfileMetric": (
        "log_filas",
        "razon_salida_entrada",
        "tasa_nulos",
        "tasa_nan",
        "prop_duplicados",
        "cardinalidad_rel",
        "expansion_union",
        "claves_sin_pareja",
        "conversiones_fallidas",
        "fechas_invalidas",
    ),
    "TimeUnit": ("s", "ms", "us", "ns"),
    "VerificationState": (
        "passed",
        "failed",
        "not_evaluable",
        "not_requested",
        "pending_review",
    ),
}
CONSTANTS = {
    "CANONICALIZATION": "equiframe-metadata-json-v1",
    "SCHEMA_VERSION": "1.0",
    "__version__": "0.12.0a13",
}
SOURCES = (
    "contracts.py",
    "types.py",
    "rule_types.py",
    "profile_types.py",
    "values.py",
    "verify_types.py",
    "serialization.py",
    "__init__.py",
)


def canonical(value):
    return json.dumps(
        value, ensure_ascii=True, sort_keys=True, separators=(",", ":"), allow_nan=False
    )


def load_inputs(args):
    op.require(op.digest(args.baseline) == boundary.BASELINE, "Baseline differs")
    baseline = op.read(args.baseline)
    op.baseline_identity(baseline, boundary.WHEEL)
    previous = []
    hashes = []
    for path, expected in zip(args.prior_result, args.prior_sha256, strict=True):
        op.require(op.digest(path) == expected, "Prior receipt differs")
        result = op.read(path)
        op.require(
            result["package"]["wheel_sha256"] == boundary.WHEEL,
            "Prior candidate differs",
        )
        previous.extend(result["receipts"])
        hashes.append(expected)
    op.require(
        boundary.aggregate(baseline, previous, [])["verified"] == 5786,
        "Prior union differs",
    )
    return baseline, previous, hashes


def prepare(baseline, previous, ef):
    closed = {row["id"] for row in baseline["rows"] if row["status"] != "NOT_RUN"}
    closed.update(
        identifier for receipt in previous for identifier in receipt["obligations"]
    )
    pending = {row["id"] for row in baseline["rows"]} - closed
    cases = []
    for name, values in LITERALS.items():
        root_id = "api:equiframe." + name
        for index, value in enumerate(values):
            links = [root_id + ":value:" + canonical(value)]
            if index == 0:
                links.append(root_id)
            links = [identifier for identifier in links if identifier in pending]
            if links:
                cases.append(
                    {
                        "case_id": f"public-type.{name}.{value}",
                        "operation": "alias",
                        "name": name,
                        "input": value,
                        "expected": value,
                        "obligations": links,
                        "basis": "Reviewed A13 Literal alternatives; TypeAdapter admission and JSON identity only",
                    }
                )
        # Guardrails exercise rejection as well, without inventing an obligation
        # absent from the frozen inventory or crediting these as new coverage.
        cases.append(
            {
                "case_id": f"public-type.{name}.invalid",
                "operation": "alias_rejection",
                "name": name,
                "input": "__unsupported_public_type__",
                "expected": "literal_error",
                "obligations": [],
                "basis": "Value absent from the independently reviewed literal alternatives",
            }
        )
    for name, value in CONSTANTS.items():
        identifier = "api:equiframe." + name
        if identifier in pending:
            cases.append(
                {
                    "case_id": "public-constant." + name,
                    "operation": "constant",
                    "name": name,
                    "expected": value,
                    "obligations": [identifier],
                    "basis": "Literal A13 constant in reviewed package source",
                }
            )
    package = Path(ef.__file__).resolve().parent
    return {
        "schema": "equiframe.public-types-catalog.v1",
        "wheel_sha256": boundary.WHEEL,
        "baseline_sha256": boundary.BASELINE,
        "declaration_source_hashes": {
            name: op.digest(package / name) for name in SOURCES
        },
        "cases": cases,
        "scope": "Public finite type admission and constants; metadata only, no detector or engine outcome inferred",
    }


def execute(case, ef):
    from pydantic import TypeAdapter, ValidationError

    observed = None
    try:
        if case["operation"] == "constant":
            observed = getattr(ef, case["name"])
        else:
            adapter = TypeAdapter(getattr(ef, case["name"]))
            value = adapter.validate_json(canonical(case["input"]), strict=True)
            observed = json.loads(adapter.dump_json(value))
        status = (
            "PASS"
            if case["operation"] != "alias_rejection"
            and canonical(observed) == canonical(case["expected"])
            else "FAIL"
        )
    except ValidationError as error:
        observed = [
            {"loc": list(item["loc"]), "type": item["type"]} for item in error.errors()
        ]
        status = (
            "EXPECTED_REJECTION"
            if case["operation"] == "alias_rejection"
            and observed
            and all(
                item["type"] == case["expected"] and item["loc"] == []
                for item in observed
            )
            else "FAIL"
        )
    except Exception as error:  # noqa: BLE001 - unexpected exceptions never earn points
        observed, status = {"unexpected_exception": type(error).__name__}, "FAIL"
    return {**case, "observed": observed, "status": status}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("mode", choices=("plan", "run"))
    for key in ("wheel", "baseline", "catalog", "output"):
        parser.add_argument("--" + key, type=Path, required=True)
    parser.add_argument("--prior-result", action="append", type=Path, required=True)
    parser.add_argument("--prior-sha256", action="append", required=True)
    parser.add_argument("--catalog-sha256")
    args = parser.parse_args()
    baseline, previous, prior_hashes = load_inputs(args)
    import equiframe as ef

    package = op.identity(
        args.wheel, boundary.WHEEL, Path(__file__).resolve().parents[1]
    )
    catalog = prepare(baseline, previous, ef)
    boundary.aggregate(
        baseline, previous, [{**case, "status": "PASS"} for case in catalog["cases"]]
    )
    if args.mode == "plan":
        boundary.write(args.catalog, catalog)
        print(
            canonical(
                {
                    "executed": False,
                    "planned_cases": len(catalog["cases"]),
                    "planned_obligations": sum(
                        len(case["obligations"]) for case in catalog["cases"]
                    ),
                    "catalog_sha256": op.digest(args.catalog),
                }
            )
        )
        return 0
    op.require(
        args.catalog_sha256
        and op.digest(args.catalog) == args.catalog_sha256
        and canonical(op.read(args.catalog)) == canonical(catalog),
        "Frozen catalog differs",
    )
    args.output.mkdir(parents=True, exist_ok=False)
    receipts = [execute(case, ef) for case in catalog["cases"]]
    summary = boundary.aggregate(baseline, previous, receipts)
    result = {
        "schema": "equiframe.public-types-result.v1",
        "candidate": ef.__version__,
        "package": package,
        "catalog_sha256": args.catalog_sha256,
        "baseline_sha256": boundary.BASELINE,
        "prior_sha256": prior_hashes,
        "tool_sha256": op.digest(Path(__file__)),
        "dependencies": {
            "boundary_tool_sha256": op.digest(Path(boundary.__file__)),
            "operations_tool_sha256": op.digest(Path(op.__file__)),
        },
        "python": sys.version,
        "platform": platform.platform(),
        "optimized": bool(sys.flags.optimize),
        "receipts": receipts,
        "summary": summary,
        "scope": catalog["scope"],
        "human_review": False,
    }
    boundary.write(args.output / "result.json", result)
    print(
        canonical(
            {
                key: value
                for key, value in summary.items()
                if key != "linked_obligations"
            }
        )
    )
    return 1 if summary["case_counts"].get("FAIL") else 0


if __name__ == "__main__":
    raise SystemExit(main())
